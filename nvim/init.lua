-- tree-sitter languages. Gitignored and generated by `install.sh --lang`; a bare
-- require would throw and abort the REST of this chunk, silently dropping every
-- module below it. Degrade the way globals.lua does.
do
  local ok, err = pcall(require, 'languages')
  if not ok then
    -- first line only: the searcher's full path dump would be a wall of toast
    vim.notify('nvim/lua/languages.lua did not load — run install.sh --lang sui|aptos\n'
      .. tostring(err):match('^[^\n]*'), vim.log.levels.WARN)
  end
end

